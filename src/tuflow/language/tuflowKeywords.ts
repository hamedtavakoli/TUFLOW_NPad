export interface NotepadPlusKeywordGroups {
  operators: string[];
  keywords: string[];
}

const nppKeywordGroups = parseNotepadPlusKeywordXml(nppTuflowKeywordXml);

export const tuflowLanguageRules = {
  caseInsensitive: true,
  lineCommentPrefixes: ['!', '#', '//'],
  operators: nppKeywordGroups.operators,
  keywords: nppKeywordGroups.keywords,
  commandLeadWords: [
    'BC',
    'Cell',
    'Control',
    'Define',
    'Event',
    'Geometry',
    'Output',
    'Read',
    'Set',
    'Write'
  ],
  includeReadWords: ['Include', 'Read', 'Geometry', 'BC', 'Event']
} as const;

export const tuflowKeywordSet = new Set(tuflowLanguageRules.keywords.map((word) => word.toLowerCase()));
export const tuflowCommandLeadWordSet = new Set(tuflowLanguageRules.commandLeadWords.map((word) => word.toLowerCase()));
export const tuflowIncludeReadWordSet = new Set(tuflowLanguageRules.includeReadWords.map((word) => word.toLowerCase()));

export function isTuflowKeyword(value: string): boolean {
  return tuflowKeywordSet.has(value.toLowerCase());
}

export function parseNotepadPlusKeywordXml(xml: string): NotepadPlusKeywordGroups {
  const groups = Array.from(xml.matchAll(/<Keywords name="([^"]+)">([\s\S]*?)<\/Keywords>/g));
  const keywords = groups
    .filter((match) => match[1] === 'Keywords2')
    .flatMap((match) => splitWords(match[2]));
  const operators = groups
    .filter((match) => match[1] === 'Keywords1')
    .flatMap((match) => splitWords(match[2]));

  return {
    operators: uniqueWords(operators.join(' ')),
    keywords: uniqueWords(keywords.join(' '))
  };
}

function uniqueWords(text: string): string[] {
  return Array.from(new Set(splitWords(text))).sort((a, b) => a.localeCompare(b));
}

function splitWords(text: string): string[] {
  return text.split(/\s+/).map((word) => word.trim()).filter(Boolean);
}
